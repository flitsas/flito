-- ── Paso 1 — El catalogo de funciones (AC1) ─────────────────────────────────────────────────────
-- `codigo` es PK textual e inmutable, igual que en `permisos_roles`: es el literal que la #12082 va
-- a comparar en cada guarda. Lo editable es `nombre_negocio`.
-- `activo` permite retirar una funcion sin borrarla — borrarla la impide el RESTRICT del paso 2 en
-- cuanto alguien la tenga concedida, y eso es deliberado.
CREATE TABLE IF NOT EXISTS permisos_funciones (
  codigo         varchar(80)  PRIMARY KEY,
  modulo         varchar(40)  NOT NULL,
  nombre_negocio varchar(120) NOT NULL,
  descripcion    text         NOT NULL,
  tipo           varchar(10)  NOT NULL,
  activo         boolean      NOT NULL DEFAULT true,
  CONSTRAINT permisos_funciones_tipo_chk CHECK (tipo IN ('pagina','operacion'))
);

CREATE INDEX IF NOT EXISTS idx_permisos_funciones_modulo ON permisos_funciones(modulo);

COMMENT ON TABLE permisos_funciones IS
  'Catalogo de funciones del producto (HU #12081). Lo declara el PRODUCTO y lo siembra esta '
  'migracion (CF-23): el administrador reparte funciones, no las inventa. Se genera desde el codigo '
  'con npm run permisos:seed -w apps/api.';
COMMENT ON COLUMN permisos_funciones.codigo IS
  'pagina.<slug> para las pantallas, <modulo>.<objeto>.<accion> para las operaciones. Inmutable.';
COMMENT ON COLUMN permisos_funciones.modulo IS
  'Agrupador de pantalla: el grupo de PAGE_GROUPS en las paginas, el modulo FLITO en las operaciones.';
COMMENT ON COLUMN permisos_funciones.tipo IS
  'pagina | operacion. Las 43 de tipo pagina son los 44 slugs de PAGES MENOS flito_ayuda, cuya '
  'visibilidad es derivada y no se concede a mano (AC2-bis).';

-- ── Paso 2 — Lo que concede un ROL (AC1) ────────────────────────────────────────────────────────
-- Las dos clausulas ON DELETE son asimetricas a proposito (ADR-0005): CASCADE hacia el rol —borrar
-- un rol se lleva su reparto, que sin el no significa nada— y RESTRICT hacia la funcion —una funcion
-- concedida no se borra por accidente; primero se retira de quien la tenga—.
-- ON UPDATE RESTRICT en las dos: los dos codigos son inmutables y que lo diga la definicion vale mas
-- que un comentario.
CREATE TABLE IF NOT EXISTS permisos_rol_funcion (
  rol_codigo     varchar(40) NOT NULL REFERENCES permisos_roles(codigo)
                   ON UPDATE RESTRICT ON DELETE CASCADE,
  funcion_codigo varchar(80) NOT NULL REFERENCES permisos_funciones(codigo)
                   ON UPDATE RESTRICT ON DELETE RESTRICT,
  PRIMARY KEY (rol_codigo, funcion_codigo)
);

-- La PK ya indexa por rol_codigo; este indice es el otro sentido, el que la pantalla de la #12084
-- necesita para «quien tiene esta funcion» y el que pide el RESTRICT al borrar una funcion.
CREATE INDEX IF NOT EXISTS idx_permisos_rol_funcion_funcion ON permisos_rol_funcion(funcion_codigo);

COMMENT ON TABLE permisos_rol_funcion IS
  'Reparto rol x funcion (HU #12081). El backfill de esta migracion reproduce exactamente el estado '
  'de hoy (CF-16): ROLE_DEFAULT_PAGES para las paginas y las guardas requireRole para las operaciones.';

-- ── Paso 3 — La excepcion por USUARIO (AC1) ─────────────────────────────────────────────────────
-- `efecto` nace con los dos valores aunque esta HU solo siembre 'conceder' (AC4): partir el modelo
-- en dos migraciones obligaria a reescribir la PK mas adelante. Quien escribe 'revocar' es la HU de
-- permisos por usuario, y hasta entonces la tabla no debe tener ni una fila con ese efecto.
CREATE TABLE IF NOT EXISTS permisos_usuario_funcion (
  user_id        integer     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  funcion_codigo varchar(80) NOT NULL REFERENCES permisos_funciones(codigo)
                   ON UPDATE RESTRICT ON DELETE RESTRICT,
  efecto         varchar(8)  NOT NULL,
  PRIMARY KEY (user_id, funcion_codigo),
  CONSTRAINT permisos_usuario_funcion_efecto_chk CHECK (efecto IN ('conceder','revocar'))
);

COMMENT ON TABLE permisos_usuario_funcion IS
  'Excepcion por usuario sobre lo que le da su rol (HU #12081). Esta migracion solo siembra '
  'conceder, desde users.allowed_pages; revocar llega con la HU de permisos por usuario.';

