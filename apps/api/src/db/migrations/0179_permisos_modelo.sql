-- ── Paso 5 — Backfill de los permisos por usuario (AC4) ─────────────────────────────────────────
-- Una fila ('conceder', pagina.<slug>) por cada entrada VALIDA de users.allowed_pages.
--
-- «Valida» es el EXISTS contra el catalogo, y hace dos trabajos a la vez: descarta los slugs que ya
-- no existen (los que `isValidPage` filtra hoy en getEffectivePages, que por eso nunca concedian
-- nada) y descarta `flito_ayuda` si alguien lo tuviera escrito a mano — no es concedible, asi que
-- sembrarlo crearia una casilla que miente. Sin el EXISTS esto reventaria con un 23503, que es la
-- otra forma de decir lo mismo pero a mitad de la migracion.
--
-- DISTINCT y no solo ON CONFLICT: un `allowed_pages` con el mismo slug repetido produciria dos filas
-- identicas en la MISMA sentencia, y eso el ON CONFLICT no lo tapa.
--
-- OJO, y hay que saberlo antes de tocar nada: esta tabla se SIEMBRA aqui y NO LA LEE NADIE todavia.
-- El alta y la edicion de usuarios siguen escribiendo `users.allowed_pages` (users.routes.ts:381 y
-- :503), y de ahi es de donde `paginasEfectivasDeUsuario` toma las paginas propias de cada usuario.
-- Es deliberado: leer esta tabla sin haber movido el camino de ESCRITURA congelaria los permisos por
-- usuario en la foto de hoy — el administrador concederia una pagina, la columna cambiaria y el
-- usuario no veria nada distinto. Lo que esta HU SI enciende es la mitad del ROL
-- (`permisos_rol_funcion`), que es la que repone las paginas de `admin` al retirar sus dos atajos.
-- Las dos mitades se juntan en la HU de permisos por usuario, que es tambien quien estrena `revocar`.
INSERT INTO permisos_usuario_funcion (user_id, funcion_codigo, efecto)
SELECT DISTINCT u.id, 'pagina.' || s.slug, 'conceder'
  FROM users u
  CROSS JOIN LATERAL unnest(u.allowed_pages) AS s(slug)
 WHERE EXISTS (SELECT 1 FROM permisos_funciones f WHERE f.codigo = 'pagina.' || s.slug)
ON CONFLICT (user_id, funcion_codigo) DO NOTHING;

-- ── Paso 6 — La cuenta, en el log del CD ────────────────────────────────────────────────────────
-- No es telemetria: es lo que permite leer en el log del despliegue si el reparto llego entero, y en
-- particular si `admin` quedo con TODAS sus funciones. Los dos atajos cableados que hoy le dan todo
-- (getEffectivePages y la fila admin de ROLE_DEFAULT_PAGES) se retiran en el mismo PR que esta
-- migracion: si estas marcas no estan, el administrador se queda sin una sola pantalla.
DO $resumen$
DECLARE
  n_funciones int; n_reparto int; n_admin int; n_usuario int; n_revocar int;
BEGIN
  SELECT count(*) INTO n_funciones FROM permisos_funciones;
  SELECT count(*) INTO n_reparto   FROM permisos_rol_funcion;
  SELECT count(*) INTO n_admin     FROM permisos_rol_funcion WHERE rol_codigo = 'admin';
  SELECT count(*) INTO n_usuario   FROM permisos_usuario_funcion;
  SELECT count(*) INTO n_revocar   FROM permisos_usuario_funcion WHERE efecto = 'revocar';
  IF n_admin = 0 THEN
    RAISE EXCEPTION '0179: el rol admin quedo sin ninguna funcion — retirar los atajos lo dejaria sin pantallas';
  END IF;
  IF n_revocar > 0 THEN
    RAISE EXCEPTION '0179: hay % filas con efecto revocar y esta HU no siembra ninguna', n_revocar;
  END IF;
  RAISE NOTICE '0179: % funciones, % filas de reparto (% de admin), % permisos por usuario',
    n_funciones, n_reparto, n_admin, n_usuario;
END $resumen$;
